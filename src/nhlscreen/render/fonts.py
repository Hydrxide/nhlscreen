@dataclass(frozen=True)
class Glyph:
    width: int
    pixels: tuple[tuple[int, int], ...]  # (dx, dy) of lit pixels


class Font:
    def __init__(self, name: str, raw: dict[str, list[str]], space_width: int, spacing: int = 1) -> None:
        self.name = name
        self.height = len(raw["A"])
        self.line_height = self.height + 1
        self.spacing = spacing
        self._glyphs: dict[str, Glyph] = {" ": Glyph(space_width, ())}
        for ch, rows in raw.items():
            if len(rows) != self.height or len({len(r) for r in rows}) != 1:
                raise ValueError(f"{name} glyph {ch!r} has inconsistent rows")
            lit = [(x, y) for y, row in enumerate(rows) for x, c in enumerate(row) if c == "#"]
            if ch.isdigit():  # tabular digits: keep the full cell so numbers align
                left, width = 0, len(rows[0])
            else:
                left = min(x for x, _ in lit)
                width = max(x for x, _ in lit) - left + 1
            self._glyphs[ch] = Glyph(width, tuple((x - left, y) for x, y in lit))

    @staticmethod
    def normalize(text: str) -> str:
        """Uppercase plain ASCII: 'Lafrenière' -> 'LAFRENIERE'."""
        plain = unicodedata.normalize("NFKD", text).encode("ascii", "ignore").decode()
        return plain.upper()

    def glyph(self, ch: str) -> Glyph:
        return self._glyphs.get(ch) or self._glyphs["?"]

    def measure(self, text: str, scale: int = 1) -> int:
        text = self.normalize(text)
        if not text:
            return 0
        return (sum(self.glyph(c).width + self.spacing for c in text) - self.spacing) * scale

    def char_advance(self, ch: str, scale: int = 1) -> int:
        return (self.glyph(ch).width + self.spacing) * scale


REGULAR = Font("regular", _REGULAR, space_width=3)
SMALL = Font("small", _SMALL, space_width=2)
